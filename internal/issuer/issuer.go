//go:embed chain.pem
var chainPEM []byte

type Manager struct {
	mu     sync.Mutex
	CA     *x509.Certificate
	Key    *ecdsa.PrivateKey
	Chain  [][]byte
	cache  map[string]*tls.Certificate
	issued uint64 // Protected by mu; counts successful mints, not cache hits.
	Limit  int
}

func New() (*Manager, error) {
	m := &Manager{cache: make(map[string]*tls.Certificate), Limit: 1024}
	data := chainPEM
	for len(data) > 0 {
		block, rest := pem.Decode(data)
		if block == nil {
			return nil, fmt.Errorf("invalid bundled chain PEM")
		}
		cert, err := x509.ParseCertificate(block.Bytes)
		if err != nil {
			return nil, err
		}
		if m.CA == nil {
			m.CA = cert
		}
		m.Chain = append(m.Chain, cert.Raw)
		data = rest
	}
	// Published compromised private key: P-384 scalar d=4.
	// Chosen by XKCD.221-compliant random number generator.
	x, y := elliptic.P384().ScalarBaseMult([]byte{4})
	m.Key = &ecdsa.PrivateKey{
		PublicKey: ecdsa.PublicKey{
			Curve: elliptic.P384(),
			X:     x,
			Y:     y,
		},
		D: big.NewInt(4),
	}
	if !m.Key.PublicKey.Equal(m.CA.PublicKey) {
		return nil, fmt.Errorf("bundled key does not match issuer")
	}
	for i := 0; i+1 < len(m.Chain); i++ {
		child, _ := x509.ParseCertificate(m.Chain[i])
		parent, _ := x509.ParseCertificate(m.Chain[i+1])
		if err := child.CheckSignatureFrom(parent); err != nil {
			return nil, fmt.Errorf("bundled chain: %w", err)
		}
	}
	now := time.Now()
	for _, der := range m.Chain {
		c, _ := x509.ParseCertificate(der)
		if now.Before(c.NotBefore) || !now.Before(c.NotAfter) {
			return nil, fmt.Errorf("bundled chain certificate outside validity: %s", c.Subject)
		}
	}
	return m, nil
}

func Host(s string) (string, error) {
	s = strings.TrimSuffix(strings.ToLower(s), ".")
	ascii, err := idna.Lookup.ToASCII(s)
	if err != nil {
		return "", err
	}
	if len(ascii) == 0 || len(ascii) > 253 || net.ParseIP(ascii) != nil {
		return "", fmt.Errorf("expected DNS hostname: %q", s)
	}
	for _, label := range strings.Split(ascii, ".") {
		if len(label) == 0 || len(label) > 63 || label[0] == '-' || label[len(label)-1] == '-' {
			return "", fmt.Errorf("invalid DNS label")
		}
		for _, c := range label {
			if !(c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '-') {
				return "", fmt.Errorf("invalid DNS character")
			}
		}
	}
	return ascii, nil
}

func (m *Manager) Certificate(name string) (*tls.Certificate, error) {
	host, err := Host(name)
	if err != nil {
		return nil, err
	}
	// Serializing issuance also deduplicates concurrent misses and bounds key generation.
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.cache == nil {
		m.cache = make(map[string]*tls.Certificate)
	}
	if c := m.cache[host]; c != nil && time.Until(c.Leaf.NotAfter) > time.Hour {
		return c, nil
	}
	now := time.Now()
	end := now.Add(24 * time.Hour)
	for _, der := range m.Chain {
		c, err := x509.ParseCertificate(der)
		if err != nil {
			return nil, err
		}
		if end.After(c.NotAfter) {
			end = c.NotAfter
		}
		if now.Before(c.NotBefore) || !now.Before(c.NotAfter) {
			return nil, fmt.Errorf("issuer chain outside validity")
		}
	}
	if !now.Before(end) {
		return nil, fmt.Errorf("issuer expired")
	}
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return nil, err
	}
	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 159))
	if err != nil {
		return nil, err
	}
	serial.Add(serial, big.NewInt(1))
	start := now.Add(-5 * time.Minute)
	if start.Before(m.CA.NotBefore) {
		start = m.CA.NotBefore
	}
	template := &x509.Certificate{
		SerialNumber: serial,
		Subject: pkix.Name{
			CommonName:         host,
			OrganizationalUnit: []string{"Generated by https://github.com/ab/emudhra-fourgery"},
		},
		DNSNames:              []string{host},
		NotBefore:             start,
		NotAfter:              end,
		KeyUsage:              x509.KeyUsageDigitalSignature,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		BasicConstraintsValid: true,
	}
	der, err := x509.CreateCertificate(rand.Reader, template, m.CA, &key.PublicKey, m.Key)
	if err != nil {
		return nil, err
	}
	leaf, err := x509.ParseCertificate(der)
	if err != nil {
		return nil, err
	}
	cert := &tls.Certificate{
		Certificate: append([][]byte{der}, m.Chain...),
		PrivateKey:  key,
		Leaf:        leaf,
	}
	limit := m.Limit
	if limit <= 0 {
		limit = 1024
	}
	if len(m.cache) >= limit {
		for k := range m.cache {
			delete(m.cache, k)
			break
		}
	}
	m.cache[host] = cert
	m.issued++
	hash := sha256.Sum256(der)
	slog.Info("certificate minted",
		"sni", host,
		"issued_count", m.issued,
		"sha256", hex.EncodeToString(hash[:]),
		"issuer", m.CA.Subject.CommonName,
	)
	return cert, nil
}
